function translatePage(language: Language) {
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  const nodes: Text[] = [];
  while (walker.nextNode()) nodes.push(walker.currentNode as Text);
  nodes.forEach((node) => {
    const element = node.parentElement;
    if (!element || ["SCRIPT", "STYLE"].includes(element.tagName)) return;
    const original = originalText.get(node) ?? node.nodeValue?.trim();
    if (!original || !ru[original]) return;
    originalText.set(node, original);
    const current = node.nodeValue?.trim() ?? "";
    node.nodeValue = node.nodeValue?.replace(current, language === "ru" ? ru[original] : original) ?? "";
  });
  document.querySelectorAll<HTMLInputElement | HTMLTextAreaElement>("[placeholder]").forEach((element) => {
    const original = originalPlaceholders.get(element) ?? element.placeholder;
    originalPlaceholders.set(element, original);
    if (ru[original]) element.placeholder = language === "ru" ? ru[original] : original;
  });
  document.documentElement.lang = language;
}

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const pathname = usePathname();
  const [language, setLanguageState] = useState<Language>("uk");
  const skippedInitialPathname = useRef(false);
  const languageRef = useRef<Language>("uk");
  useEffect(() => {
    const stored = window.localStorage.getItem("drivestate-language");
    const initial = stored === "ru" ? "ru" : "uk";
    languageRef.current = initial;
    if (initial !== "ru") {
      document.documentElement.lang = "uk";
      return;
    }
    const timer = window.setTimeout(() => {
      setLanguageState(initial);
      translatePage(initial);
    }, 500);
    return () => window.clearTimeout(timer);
  }, []);
  useEffect(() => {
    if (!skippedInitialPathname.current) {
      skippedInitialPathname.current = true;
      return;
    }
    const timer = window.setTimeout(() => translatePage(languageRef.current), 100);
    return () => window.clearTimeout(timer);
  }, [pathname]);
  const value = useMemo(
    () => ({
      language,
      setLanguage: (next: Language) => {
        languageRef.current = next;
        setLanguageState(next);
        window.localStorage.setItem("drivestate-language", next);
        translatePage(next);
      },
    }),
    [language],
  );
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  return useContext(LanguageContext);
}
